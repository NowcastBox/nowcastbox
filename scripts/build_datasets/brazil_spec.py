"""Specification of the Brazilian nowcasting panel (``load_brazil_nowcast``).

Each entry names one series, its primary source and code, the named stationarity
transformation (``nowcastbox.preprocessing`` syntax), the typical publication delay in
days after the end of the reference period, the factor blocks and the category.

Only sources with open terms of use are included (BCB open-data portal, ODbL; IBGE;
IPEADATA, citing the source; federal government agencies). Series compiled by private
associations or survey firms (FGV, CNI, ANFAVEA, FENABRAVE, ABPO, Aço Brasil,
Fecomercio, ...) are deliberately excluded from the shipped panel because their
redistribution terms are unclear; they remain reachable through the connectors.

Delays are *stylised* typical lags read from the 2024-2026 release calendars of IBGE,
BCB, IPEA and the ministries (the vintage tools treat them as exact): the observation of
period ``p`` is assumed public ``delay`` days after the last day of ``p``.
"""

