r"""Bootstrap of the parameter uncertainty of a nowcast (innovation I5).

The Kalman smoother delivers the predictive variance of the nowcast *given* the
estimated parameters :math:`\hat\theta`. To account for the estimation error the
parameters are bootstrapped (Stoffer & Wall, 1991; Pfeffermann & Tiller, 2005;
Rodríguez & Ruiz, 2012):

1. draw a pseudo-panel :math:`X^{*}_b` with the missing-data pattern of the original
   panel, either

   * ``method="parametric"`` - simulated from the fitted state-space model
     (:math:`\alpha_{t+1} = T\alpha_t + R\eta_t`, :math:`x_t = Z\alpha_t + \varepsilon_t`;
     for the two-step model the target is generated by the fitted bridge equation
     :math:`y^Q_t = \hat\alpha + \hat\beta'\bar f^Q_t + \hat\sigma_e e_t`), or
   * ``method="block"`` - a moving-block bootstrap of whole target periods (Künsch,
     1989), model-free and available for every estimator;

2. re-estimate the model on :math:`X^{*}_b`, giving :math:`\hat\theta^{*}_b`;
3. run the smoother with :math:`\hat\theta^{*}_b` **on the original data**, giving the
   nowcast :math:`\hat y_t(\hat\theta^{*}_b)` and its smoothing standard deviation
   :math:`s_t(\hat\theta^{*}_b)`.

The spread of :math:`\hat y_t(\hat\theta^{*}_b)` across replications measures the
parameter uncertainty; :func:`nowcastbox.density.nowcast_distribution` combines both
sources into a Gaussian mixture.

Replications use independent child seeds of :class:`numpy.random.SeedSequence`, so the
draws do not depend on ``n_jobs``.

References
----------
Stoffer, D. S. & Wall, K. D. (1991). Bootstrapping state-space models: Gaussian maximum
likelihood estimation and the Kalman filter. *JASA*, 86(416), 1024-1033.

Pfeffermann, D. & Tiller, R. (2005). Bootstrap approximation to prediction MSE for
state-space models with estimated parameters. *Journal of Time Series Analysis*,
26(6), 893-916.

Rodríguez, A. & Ruiz, E. (2012). Bootstrap prediction mean squared errors of
unobserved states based on the Kalman filter with estimated parameters.
*Computational Statistics & Data Analysis*, 56(1), 62-74.

Künsch, H. R. (1989). The jackknife and the bootstrap for general stationary
observations. *Annals of Statistics*, 17(3), 1217-1241.
"""

